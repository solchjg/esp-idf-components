#!/usr/bin/env python3
"""Convert a 16x32 character-cell BDF font (ASCII 0x20-0x7E) to a C table.

Usage: bdf_to_c.py ter-u32b.bdf > components/lcd/font16x32.c

Each glyph is 32 rows of uint16_t, bit 15 = leftmost pixel. Only fonts whose
every glyph fills the full 16x32 cell are accepted, so no glyph is offset.
"""

import sys

FIRST, LAST, W, H = 0x20, 0x7E, 16, 32


def glyphs(path):
    out, cur = {}, None
    with open(path) as fh:
        for line in fh:
            tok = line.split()
            if not tok:
                continue
            if tok[0] == "ENCODING":
                cur = {"enc": int(tok[1]), "rows": None}
            elif tok[0] == "BBX" and cur is not None:
                if [int(v) for v in tok[1:3]] != [W, H]:
                    sys.exit(f"glyph {cur['enc']:#x} is not a {W}x{H} cell")
            elif tok[0] == "BITMAP" and cur is not None:
                cur["rows"] = []
            elif tok[0] == "ENDCHAR" and cur is not None:
                out[cur["enc"]] = cur["rows"]
                cur = None
            elif cur is not None and cur["rows"] is not None:
                cur["rows"].append(int(tok[0], 16))
    return out


def main(path):
    g = glyphs(path)
    print("// Generated by tools/bdf_to_c.py from Terminus Font Bold 16x32 (ter-u32b.bdf,")
    print("// terminus-font 4.49.1). Copyright (C) 2020 Dimitar Toshkov Zhekov.")
    print("// Licensed under the SIL Open Font License 1.1: see font/OFL.txt.")
    print("// Do not edit: regenerate instead.\n")
    print('#include "lcd_text.h"\n')
    print("const uint16_t font16x32[FONT_GLYPHS][FONT_H] = {")
    for c in range(FIRST, LAST + 1):
        rows = g.get(c)
        if rows is None or len(rows) != H:
            sys.exit(f"glyph {c:#x} missing or not {H} rows")
        body = ", ".join(f"0x{r:04x}" for r in rows)
        label = chr(c).replace("\\", "backslash")
        print(f"    /* {c:#04x} {label} */ {{{body}}},")
    print("};")


if __name__ == "__main__":
    main(sys.argv[1])
