#!/usr/bin/env python3
"""Convert a character-cell BDF font (ASCII 0x20-0x7E) to a C table.

Usage:
  bdf_to_c.py ter-u32b.bdf > components/text/font16x32.c
  bdf_to_c.py ter-u24b.bdf 12x24 > components/text/font12x24.c

Each glyph is H rows of uint16_t, bit 15 = leftmost pixel (cells up to 16
wide). Only fonts whose every glyph fills the full WxH cell are accepted, so
no glyph is offset. The table is named fontWxH and sized by FONT_GLYPHS and H.
"""

import sys

FIRST, LAST = 0x20, 0x7E
SOURCES = {(16, 32): "ter-u32b.bdf", (12, 24): "ter-u24b.bdf"}


def glyphs(path, w, h):
    out, cur = {}, None
    with open(path) as fh:
        for line in fh:
            tok = line.split()
            if not tok:
                continue
            if tok[0] == "ENCODING":
                cur = {"enc": int(tok[1]), "rows": None}
            elif tok[0] == "BBX" and cur is not None:
                if [int(v) for v in tok[1:3]] != [w, h]:
                    sys.exit(f"glyph {cur['enc']:#x} is not a {w}x{h} cell")
            elif tok[0] == "BITMAP" and cur is not None:
                cur["rows"] = []
            elif tok[0] == "ENDCHAR" and cur is not None:
                out[cur["enc"]] = cur["rows"]
                cur = None
            elif cur is not None and cur["rows"] is not None:
                cur["rows"].append(int(tok[0], 16) << (16 - 4 * len(tok[0])))
    return out


def main(path, size="16x32"):
    w, h = (int(v) for v in size.split("x"))
    if w > 16:
        sys.exit("cells wider than 16 pixels do not fit a uint16_t row")
    g = glyphs(path, w, h)
    src = SOURCES.get((w, h), path.rsplit("/", 1)[-1])
    rows_name = "FONT_H" if (w, h) == (16, 32) else str(h)
    print(f"// Generated by tools/bdf_to_c.py from Terminus Font Bold {w}x{h} ({src},")
    print("// terminus-font 4.49.1). Copyright (C) 2020 Dimitar Toshkov Zhekov.")
    print("// Licensed under the SIL Open Font License 1.1: see font/OFL.txt.")
    print("// Do not edit: regenerate instead.\n")
    print('#include "text.h"\n')
    print(f"const uint16_t font{w}x{h}[FONT_GLYPHS][{rows_name}] = {{")
    for c in range(FIRST, LAST + 1):
        rows = g.get(c)
        if rows is None or len(rows) != h:
            sys.exit(f"glyph {c:#x} missing or not {h} rows")
        body = ", ".join(f"0x{r:04x}" for r in rows)
        label = chr(c).replace("\\", "backslash")
        print(f"    /* {c:#04x} {label} */ {{{body}}},")
    print("};")


if __name__ == "__main__":
    main(*sys.argv[1:3])
